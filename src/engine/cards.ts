export function cardById(id: string): CardDef {
  const c = CARD_MAP[id];
  if (!c) throw new Error(`Unknown card ${id}`);
  return c;
}

export function weaponById(id: string): WeaponDef {
  const w = WEAPON_MAP[id];
  if (!w) throw new Error(`Unknown weapon ${id}`);
  return w;
}

export function pitchLabel(pitch: number, color: CardDef["color"]): string {
  if (color === "red" || pitch === 1) return "R";
  if (color === "yellow" || pitch === 2) return "Y";
  if (color === "blue" || pitch === 3) return "B";
  return "—";
}
